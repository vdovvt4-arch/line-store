CREATE OR REPLACE FUNCTION public.place_order(
  p_order jsonb,
  p_customer jsonb,
  p_items jsonb,
  p_coupon_id bigint DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_order_id bigint;
  v_item jsonb;
  v_product public.products%ROWTYPE;
  v_product_id bigint;
  v_qty integer;
  v_size text;
  v_size_stock integer;
  v_next_sizes jsonb;
  v_next_stock integer;
BEGIN
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Invalid order items' USING ERRCODE = '22023';
  END IF;
  IF jsonb_array_length(p_items) = 0 OR jsonb_array_length(p_items) > 20 THEN
    RAISE EXCEPTION 'Invalid order items' USING ERRCODE = '22023';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    v_product_id := (v_item ->> 'product_id')::bigint;
    v_qty := (v_item ->> 'qty')::integer;
    v_size := COALESCE(v_item ->> 'size', '');
    IF v_qty IS NULL OR v_qty < 1 OR v_qty > 20 THEN
      RAISE EXCEPTION 'Invalid item quantity' USING ERRCODE = '22023';
    END IF;

    SELECT * INTO v_product FROM public.products WHERE id = v_product_id FOR UPDATE;
    IF NOT FOUND OR NOT v_product.published OR v_product.sold_out OR v_product.stock <= 0 THEN
      RAISE EXCEPTION 'Product is unavailable' USING ERRCODE = 'P0001';
    END IF;

    IF jsonb_typeof(v_product.sizes) = 'array' AND jsonb_array_length(v_product.sizes) > 0 THEN
      SELECT COALESCE((value ->> 'stock')::integer, 0)
      INTO v_size_stock
      FROM jsonb_array_elements(v_product.sizes) AS size_item(value)
      WHERE value ->> 'size' = v_size;
      IF NOT FOUND THEN
        RAISE EXCEPTION 'Invalid product size' USING ERRCODE = 'P0001';
      END IF;
      IF v_size_stock < v_qty THEN
        RAISE EXCEPTION 'Insufficient size stock' USING ERRCODE = 'P0001';
      END IF;

      SELECT jsonb_agg(
        CASE WHEN value ->> 'size' = v_size
          THEN jsonb_set(value, '{stock}', to_jsonb(v_size_stock - v_qty), true)
          ELSE value
        END ORDER BY ordinal
      )
      INTO v_next_sizes
      FROM jsonb_array_elements(v_product.sizes) WITH ORDINALITY AS size_item(value, ordinal);

      SELECT COALESCE(SUM((value ->> 'stock')::integer), 0)
      INTO v_next_stock
      FROM jsonb_array_elements(v_next_sizes) AS size_item(value);

      UPDATE public.products
      SET sizes = v_next_sizes,
          stock = v_next_stock,
          sold_out = CASE WHEN v_next_stock <= 0 THEN true ELSE sold_out END
      WHERE id = v_product_id;
    ELSE
      IF v_product.stock < v_qty THEN
        RAISE EXCEPTION 'Insufficient product stock' USING ERRCODE = 'P0001';
      END IF;
      UPDATE public.products
      SET stock = stock - v_qty,
          sold_out = CASE WHEN stock - v_qty <= 0 THEN true ELSE sold_out END
      WHERE id = v_product_id;
    END IF;
  END LOOP;

  INSERT INTO public.customers (phone, name, governorate, address)
  VALUES (
    p_customer ->> 'phone',
    p_customer ->> 'name',
    p_customer ->> 'governorate',
    p_customer ->> 'address'
  )
  ON CONFLICT (phone) DO UPDATE SET
    name = EXCLUDED.name,
    governorate = EXCLUDED.governorate,
    address = EXCLUDED.address;

  IF p_coupon_id IS NOT NULL THEN
    UPDATE public.coupons
    SET uses_count = uses_count + 1
    WHERE id = p_coupon_id
      AND active = true
      AND code = upper(COALESCE(p_order ->> 'coupon_code', ''));
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Coupon is unavailable' USING ERRCODE = 'P0001';
    END IF;
  END IF;

  INSERT INTO public.orders (
    product_id, product_name, size, color, items, customer_name, phone, governorate, address,
    measurements, sketch, note, coupon_code, discount_amount, price, cost_total, profit,
    delivery_fee, total
  )
  VALUES (
    NULLIF(p_order ->> 'product_id', '')::bigint,
    COALESCE(p_order ->> 'product_name', ''),
    COALESCE(p_order ->> 'size', ''),
    COALESCE(p_order ->> 'color', ''),
    COALESCE(p_order -> 'items', '[]'::jsonb),
    p_customer ->> 'name',
    p_customer ->> 'phone',
    p_customer ->> 'governorate',
    p_customer ->> 'address',
    COALESCE(p_order -> 'measurements', '{}'::jsonb),
    COALESCE(p_order ->> 'sketch', ''),
    COALESCE(p_order ->> 'note', ''),
    COALESCE(p_order ->> 'coupon_code', ''),
    COALESCE((p_order ->> 'discount_amount')::numeric, 0),
    COALESCE((p_order ->> 'price')::numeric, 0),
    COALESCE((p_order ->> 'cost_total')::numeric, 0),
    COALESCE((p_order ->> 'profit')::numeric, 0),
    COALESCE((p_order ->> 'delivery_fee')::numeric, 0),
    COALESCE((p_order ->> 'total')::numeric, 0)
  )
  RETURNING id INTO v_order_id;

  RETURN v_order_id;
END;
$$;

