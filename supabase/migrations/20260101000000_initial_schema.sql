CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  category text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  price numeric(14, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  cost_price numeric(14, 2) NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
  discount_type text NOT NULL DEFAULT 'none' CHECK (discount_type IN ('none', 'percent', 'fixed')),
  discount_value numeric(14, 2) NOT NULL DEFAULT 0 CHECK (discount_value >= 0),
  stock integer NOT NULL DEFAULT 10 CHECK (stock >= 0),
  low_stock_threshold integer NOT NULL DEFAULT 3 CHECK (low_stock_threshold >= 0),
  colors jsonb NOT NULL DEFAULT '[]'::jsonb,
  sizes jsonb NOT NULL DEFAULT '[]'::jsonb,
  images jsonb NOT NULL DEFAULT '[]'::jsonb,
  published boolean NOT NULL DEFAULT false,
  sold_out boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.customers (
  phone text PRIMARY KEY,
  name text NOT NULL DEFAULT '',
  governorate text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.coupons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  type text NOT NULL DEFAULT 'percent' CHECK (type IN ('percent', 'fixed')),
  value numeric(14, 2) NOT NULL DEFAULT 0 CHECK (value >= 0),
  min_order numeric(14, 2) NOT NULL DEFAULT 0 CHECK (min_order >= 0),
  active boolean NOT NULL DEFAULT true,
  uses_count bigint NOT NULL DEFAULT 0 CHECK (uses_count >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL DEFAULT '',
  size text NOT NULL DEFAULT '',
  color text NOT NULL DEFAULT '',
  items jsonb NOT NULL DEFAULT '[]'::jsonb,
  customer_name text NOT NULL,
  phone text NOT NULL REFERENCES public.customers(phone) ON UPDATE CASCADE,
  governorate text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  measurements jsonb NOT NULL DEFAULT '{}'::jsonb,
  sketch text NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  coupon_code text NOT NULL DEFAULT '',
  discount_amount numeric(14, 2) NOT NULL DEFAULT 0,
  price numeric(14, 2) NOT NULL DEFAULT 0,
  cost_total numeric(14, 2) NOT NULL DEFAULT 0,
  profit numeric(14, 2) NOT NULL DEFAULT 0,
  delivery_fee numeric(14, 2) NOT NULL DEFAULT 0,
  total numeric(14, 2) NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'new'
    CHECK (status IN ('new', 'confirmed', 'preparing', 'shipping', 'delivered', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.expenses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  category text NOT NULL DEFAULT 'other'
    CHECK (category IN ('rent', 'electricity', 'salary', 'marketing', 'other')),
  amount numeric(14, 2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
  note text NOT NULL DEFAULT '',
  expense_date date NOT NULL DEFAULT current_date,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.settings (
  key text PRIMARY KEY,
  value jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS products_public_order_idx ON public.products (published, id DESC);
CREATE INDEX IF NOT EXISTS orders_phone_order_idx ON public.orders (phone, id DESC);
CREATE INDEX IF NOT EXISTS expenses_date_order_idx ON public.expenses (expense_date DESC, id DESC);

